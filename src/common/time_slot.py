"""時段與節次共用函式 — F1~F5、F7 共用"""

# 節次 -> (索引, 開始, 結束)，全專案唯一的節次資料來源
PERIOD_TABLE = {
    "1": (1, "08:10", "09:00"),
    "2": (2, "09:10", "10:00"),
    "3": (3, "10:10", "11:00"),
    "4": (4, "11:10", "12:00"),
    "5": (5, "13:10", "14:00"),
    "6": (6, "14:10", "15:00"),
    "7": (7, "15:10", "16:00"),
    "8": (8, "16:10", "17:00"),
    "9": (9, "17:10", "18:00"),
    "a": (10, "18:30", "19:20"),
    "b": (11, "19:20", "20:10"),
    "c": (12, "20:20", "21:10"),
}


def period_time_range(period):
    """回傳節次的 (開始, 結束) HH:MM。"""
    _, start, end = PERIOD_TABLE[period]
    return start, end
